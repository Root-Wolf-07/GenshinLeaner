"""Chat and Citation schemas for RAG AI Tutor.
"""

from datetime import datetime
from typing import Any, Dict, List, Literal, Optional
from backend.schemas.compat import BaseModel, Field


class Citation(BaseModel):
    """Verifiable source citation contract."""
    citation_id: str
    document_id: str
    document_title: str
    source_type: str
    page_number: Optional[int] = None
    slide_number: Optional[int] = None
    start_timestamp_seconds: Optional[float] = None
    end_timestamp_seconds: Optional[float] = None
    excerpt: str


class ChatRequest(BaseModel):
    message: str = Field(..., min_length=1, max_length=10000)
    conversation_id: Optional[str] = None
    source_mode: Literal["uploaded", "general", "both"] = "both"
    selected_document_ids: Optional[List[str]] = None
    student_level: Optional[str] = None  # e.g. "middle_school", "high_school", "undergraduate", "graduate"
    response_depth: Optional[str] = "detailed"  # "simple", "step_by_step", "analogy", "detailed", "exam_prep"
    subject: Optional[str] = None


class DiagnosticCheckpoint(BaseModel):
    """Interactive checkpoint question generated by the Agentic Tutor for the student UI companion."""
    checkpoint_id: str
    prompt: str
    question_type: str = "multiple_choice"
    options: Optional[List[str]] = None
    hint: Optional[str] = None


class ChatResponse(BaseModel):
    conversation_id: str
    message_id: str
    role: str = "assistant"
    content: str
    source_mode: str
    citations: List[Citation] = Field(default_factory=list)
    insufficient_evidence: bool = False
    suggested_follow_ups: List[str] = Field(default_factory=list)
    agent_plan: List[str] = Field(default_factory=list, description="Autonomous reasoning and tool execution trace of the Agentic AI Tutor")
    pedagogical_mode: Optional[str] = "adaptive_scaffolding"
    diagnostic_checkpoint: Optional[DiagnosticCheckpoint] = None
    created_at: datetime


class MessageResponse(BaseModel):
    id: str
    conversation_id: str
    role: str
    content: str
    citations: List[Citation] = Field(default_factory=list)
    source_mode: str
    created_at: datetime

    model_config = {"from_attributes": True}


class ConversationResponse(BaseModel):
    id: str
    title: str
    source_mode: str
    selected_document_ids: List[str]
    created_at: datetime
    updated_at: datetime
    messages: Optional[List[MessageResponse]] = None

    model_config = {"from_attributes": True}
